import numpy as np

# arange
print(np.arange(0, 10))
print(np.arange(0, 10, 2))
print()

# zeros and ones
print(np.zeros(5))
print(np.zeros((2, 2)))
print(np.ones(5))
print(np.ones((2, 2)))
print()

# linspace
print(np.linspace(0, 20, 6))
print(np.linspace(0, 10, 20))
print()

# eye
print(np.eye(3))
print(np.eye(5))
